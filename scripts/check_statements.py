#!/usr/bin/env python3
"""Check the formalized statements of the paper and the axioms they depend on.

For every declaration listed in `statements.json` this script

1. elaborates it with `set_option pp.all true` (`#check @Name` for a theorem, `#print Name` for a
   definition, so a definition's body is included), collapses whitespace, and compares the SHA-256
   of the result with the recorded hash. The recorded hashes were computed from the statements
   approved by the authors, so a match means the statement is unchanged;
2. runs `#print axioms Name` and accepts only `propext`, `Classical.choice`, `Quot.sound`, plus, for
   the results that depend on the finite computation of Lemma 5.3, the axioms generated by
   `native_decide` for the checks named in `native_checks`.

Usage (from the repository root, after `lake build`):

    python3 scripts/check_statements.py           # check
    python3 scripts/check_statements.py --write   # recompute the hashes (maintainers only)

The probe file is written to a temporary directory and deleted afterwards.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "statements.json"
SEP = "@@STATEMENT@@"
AX = "@@AXIOMS@@"
STANDARD = {"propext", "Classical.choice", "Quot.sound"}


def run_probe(names: list[tuple[str, str]], module: str) -> str:
    lines = [f"import {module}", ""]
    for name, kind in names:
        lines.append(f'#print "{SEP}{name}"')
        lines.append("set_option pp.all true in")
        lines.append(f"#check @{name}" if kind == "theorem" else f"#print {name}")
        lines.append(f'#print "{AX}{name}"')
        lines.append(f"#print axioms {name}")
    with tempfile.TemporaryDirectory() as tmp:
        probe = Path(tmp) / "StatementProbe.lean"
        probe.write_text("\n".join(lines) + "\n", encoding="utf-8")
        run = subprocess.run(["lake", "env", "lean", str(probe)], cwd=ROOT,
                             capture_output=True, text=True)
    if run.returncode != 0:
        sys.exit(f"Lean failed:\n{run.stdout}{run.stderr}")
    return run.stdout


def parse(output: str) -> dict[str, tuple[str, list[str]]]:
    result = {}
    for chunk in output.split(SEP)[1:]:
        name, _, rest = chunk.partition("\n")
        statement, _, axioms = rest.partition(AX)
        axioms = axioms.partition("\n")[2]
        statement = " ".join(statement.split())
        if "does not depend on any axioms" in axioms:
            found: list[str] = []
        else:
            body = re.search(r"depends on axioms: \[(.*)\]", axioms, re.S)
            found = [a.strip().rstrip("✝") for a in body.group(1).split(",")] if body else ["?"]
        result[name.strip()] = (statement, found)
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="recompute and store the hashes")
    args = parser.parse_args()
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    decls = data["declarations"]
    native = re.compile(r"^(?:" + "|".join(re.escape(c) for c in data["native_checks"])
                        + r")\._native\.native_decide\.ax_\d+_\d+$")
    parsed = parse(run_probe([(d["name"], d["kind"]) for d in decls], data["module"]))
    failures = 0
    for d in decls:
        statement, axioms = parsed.get(d["name"], ("", ["missing"]))
        digest = hashlib.sha256(statement.encode("utf-8")).hexdigest()
        if args.write:
            d["sha256"] = digest
        ok_hash = digest == d["sha256"]
        extra = [a for a in axioms if a not in STANDARD and not (d["native"] and native.match(a))]
        n_native = sum(1 for a in axioms if native.match(a))
        ok_ax = not extra and (n_native > 0) == d["native"]
        failures += (not ok_hash) + (not ok_ax)
        flag = "ok " if ok_hash and ok_ax else "FAIL"
        print(f"{flag} {d['paper']:<34} {d['name']:<58} statement {'ok' if ok_hash else 'CHANGED'}, "
              f"axioms: standard{f' + {n_native} native' if n_native else ''}"
              + (f", unexpected {extra}" if extra else ""))
    if args.write:
        MANIFEST.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print("hashes written to", MANIFEST.name)
        return 0
    print(f"\n{len(decls)} declarations, {failures} failure(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())

"""Write the Lean modules of the kernel checks of Lemma 5.3 from the output of `kernel_data`.

Usage: python3 kernel_lean.py top.txt roots.txt <output directory DavenportCompute/Checks>

* `Top.lean`: the instruction stream of `DavenportCompute.Search.topDfs` and its check;
* `ChunkNNN.lean`: consecutive chunk roots with their certificate data and the check of
  `DavenportCompute.Search.chunkRun`;
* `Roots.lean`: all chunks, and the chunk roots listed by the top stream are theirs, in order.

Chunks are filled in order up to a budget of (nodes + 8 * certificates), which keeps the memory of
each kernel check below about two gigabytes.
"""
import sys
from pathlib import Path

sys.set_int_max_str_digits(0)
BUDGET = 16000
CERT_WEIGHT = 8
HEADER = """/-
Copyright (c) 2026 Claudiu G. Pop, George C. Rad, George C. Țurcaș. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Claudiu G. Pop, George C. Rad, George C. Țurcaș
-/
module
"""


def chunks(roots_path):
    out, cur = [], None
    for line in open(roots_path):
        head, ws = line.split("|")
        t, n, c = map(int, head.split())
        words = [int(w) for w in ws.split()]
        cost = n + CERT_WEIGHT * c
        if cur is None or cur["cost"] + cost > BUDGET:
            cur = {"roots": [], "words": [], "cost": 0, "nodes": 0, "certs": 0}
            out.append(cur)
        cur["roots"].append(t)
        cur["words"] += words
        cur["cost"] += cost
        cur["nodes"] += n
        cur["certs"] += c
    return out


def packed(words):
    d = 0
    for w in reversed(words):
        d = (d << 20) | w
    return d


def main():
    top_path, roots_path, outdir = sys.argv[1], sys.argv[2], Path(sys.argv[3])
    outdir.mkdir(parents=True, exist_ok=True)
    stream = [int(l) for l in open(top_path)]
    cs = chunks(roots_path)
    width = len(str(len(cs) - 1))
    for i, c in enumerate(cs):
        name = f"{i:0{width}d}"
        src = HEADER + f"""
public import DavenportCompute.Search

/-!
# Lemma 5.3: kernel check, chunk {i} of {len(cs)}

The tests of Lemma 5.3 below {len(c['roots'])} chunk roots ({c['nodes']} nodes of the enumeration,
{c['certs']} certificates). Generated by `scripts/l53/kernel_lean.py`; checked by `decide +kernel`.
-/

@[expose] public section

namespace DavenportCompute.Checks

open DavenportCompute.Search

/-- The chunk roots of chunk {i}. -/
def roots{name} : List Nat :=
  [{", ".join(map(str, c['roots']))}]

/-- The certificates of chunk {i}, as a stream of 20-bit words. -/
def data{name} : Nat :=
  {packed(c['words'])}

theorem chunk{name} : chunkRun roots{name} data{name} = some 0 := by decide +kernel

end DavenportCompute.Checks
"""
        (outdir / f"Chunk{name}.lean").write_text(src, encoding="utf-8")
    seg = 400
    parts = [stream[i:i + seg] for i in range(0, len(stream), seg)]
    segs = "\n\n".join(f"""/-- Part {j} of the instructions. -/
def topStream{j} : List Nat :=
  [{", ".join(map(str, p))}]""" for j, p in enumerate(parts))
    top = HEADER + f"""
public import DavenportCompute.Search

/-!
# Lemma 5.3: kernel check of the enumeration down to the chunk roots

The instructions of `DavenportCompute.Search.topDfs`: `0` to descend, otherwise the token of a chunk
root ({stream.count(0)} descents, {len(stream) - stream.count(0)} chunk roots). Generated by
`scripts/l53/kernel_lean.py`; checked by `decide +kernel`.
-/

@[expose] public section

namespace DavenportCompute.Checks

open DavenportCompute.Search

{segs}

/-- The instructions of the enumeration down to the chunk roots. -/
def topStream : List Nat :=
  [{", ".join(f"topStream{j}" for j in range(len(parts)))}].flatten

theorem top : topDfs 14 root topStream = some [] := by decide +kernel

end DavenportCompute.Checks
"""
    (outdir / "Top.lean").write_text(top, encoding="utf-8")
    names = [f"{i:0{width}d}" for i in range(len(cs))]
    imports = "\n".join(f"public import DavenportCompute.Checks.Chunk{n}" for n in names)
    group = 32
    groups = [names[i:i + group] for i in range(0, len(names), group)]
    gdefs = []
    for g, ns in enumerate(groups):
        pairs = ", ".join(f"(roots{n}, data{n})" for n in ns)
        proofs = ", ".join(f"chunk{n}" for n in ns)
        gdefs.append(f"""/-- Chunks {ns[0]} to {ns[-1]}. -/
def chunks{g} : List (List Nat × Nat) :=
  [{pairs}]

theorem chunks{g}_ok : ∀ c ∈ chunks{g}, chunkRun c.1 c.2 = some 0 := by
  simp only [chunks{g}, List.forall_mem_cons, List.not_mem_nil, false_imp_iff, implies_true, and_true]
  exact ⟨{proofs}⟩""")
    glist = ", ".join(f"chunks{g}" for g in range(len(groups)))
    gproofs = ", ".join(f"chunks{g}_ok" for g in range(len(groups)))
    roots = HEADER + f"""
public import DavenportCompute.Checks.Top
{imports}

/-!
# Lemma 5.3: the chunks

The {len(cs)} chunks with their data, the chunk roots they cover, and the fact that these are the
chunk roots listed by `topStream`, in order.
-/

@[expose] public section

namespace DavenportCompute.Checks

open DavenportCompute.Search

{chr(10).join(gdefs)}

/-- The chunks: chunk roots and certificate data. -/
def chunks : List (List Nat × Nat) :=
  [{glist}].flatten

theorem chunks_ok : ∀ c ∈ chunks, chunkRun c.1 c.2 = some 0 := by
  have h : ∀ l ∈ [{glist}], ∀ c ∈ l, chunkRun c.1 c.2 = some 0 := by
    simp only [List.forall_mem_cons, List.not_mem_nil, false_imp_iff, implies_true, and_true]
    exact ⟨{gproofs}⟩
  intro c hc
  obtain ⟨l, hl, hc⟩ := List.mem_flatten.1 hc
  exact h l hl c hc

/-- The chunk roots of all chunks. -/
def allRoots : List Nat := (chunks.map Prod.fst).flatten

theorem topStream_roots : topStream.filter (fun t => !Nat.beq t 0) = allRoots := by decide +kernel

end DavenportCompute.Checks
"""
    (outdir / "Roots.lean").write_text(roots, encoding="utf-8")
    print(f"{len(cs)} chunks, {sum(c['nodes'] for c in cs)} nodes, {sum(c['certs'] for c in cs)} certificates;"
          f" top stream {len(stream)} entries")


if __name__ == "__main__":
    main()
